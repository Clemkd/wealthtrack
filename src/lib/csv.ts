
// A text gets the protection prefix when it is a formula, or when it already looks
// like a protected one (any number of quotes before the trigger), so that
// unescaping gives back exactly what was typed.
function needsFormulaProtection(text: string): boolean {
  return /^'*[=+\-@\t\r]/.test(text);
}

// Text cells starting with a formula trigger are prefixed with a quote so that
// opening the file in a spreadsheet cannot run them. Numbers are written as is.
export function escapeCsvField(value: string | number, separator = ','): string {
  const text = typeof value === 'number' ? String(value) : value;
  const needsPrefix = typeof value === 'string' && needsFormulaProtection(text);
  return quoteCsvField(needsPrefix ? `'${text}` : text, separator);
}

// Quotes a field when needed, without formula protection: for text generated by
// the app itself (labels, formatted amounts), never for user input.
export function quoteCsvField(text: string, separator = ','): string {
  if (text.includes(separator) || /["\n\r]/.test(text)) {
    return `"${text.replace(/"/g, '""')}"`;
  }
  return text;
}

// Reverses the formula protection added by escapeCsvField.
export function unescapeCsvField(text: string): string {
  if (text[0] === "'" && needsFormulaProtection(text.slice(1))) {
    return text.slice(1);
  }
  return text;
}

export function detectDelimiter(text: string): ',' | ';' {
  let inQuotes = false;
  let commas = 0;
  let semicolons = 0;
  for (const char of text) {
    if (char === '"') inQuotes = !inQuotes;
    else if (!inQuotes && (char === '\n' || char === '\r')) break;
    else if (!inQuotes && char === ',') commas++;
    else if (!inQuotes && char === ';') semicolons++;
  }
  return semicolons > commas ? ';' : ',';
}

// RFC 4180 style parser working on the whole text, so quoted fields can contain
// delimiters, quotes and line breaks. Rows made of a single empty field are skipped.
export function parseCsv(text: string): string[][] {
  const delimiter = detectDelimiter(text);
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;

  const endRow = () => {
    row.push(field);
    field = '';
    if (!(row.length === 1 && row[0] === '')) rows.push(row);
    row = [];
  };

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      inQuotes = true;
    } else if (char === delimiter) {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      endRow();
    } else {
      field += char;
    }
  }
  if (field !== '' || row.length > 0) endRow();
  return rows;
}
